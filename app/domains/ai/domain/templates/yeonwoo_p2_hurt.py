VALID_ILGAN: frozenset[str] = frozenset(HURT_SCENARIOS_BY_ILGAN.keys())


def get_hurt_scenarios(ilgan: str) -> tuple[tuple[str, str], tuple[str, str]]:
    """일간별 상처 시나리오 2개 반환: ((when_1, desc_1), (when_2, desc_2))."""
    if ilgan not in VALID_ILGAN:
        raise KeyError(f"unknown ilgan: {ilgan!r}")
    return HURT_SCENARIOS_BY_ILGAN[ilgan]


def get_hurt_bubble(ilgan: str) -> str:
    """일간별 강연우 버블 멘트 반환."""
    if ilgan not in VALID_ILGAN:
        raise KeyError(f"unknown ilgan: {ilgan!r}")
    return HURT_BUBBLE_BY_ILGAN[ilgan]


def compose_p2_hurt(*, ilgan: str) -> dict[str, str]:
    """1-4 상처 메커니즘 풀 합성.

    Args:
        ilgan: 일간 한글 (10종)

    Returns:
        {scenario_1_when, scenario_1_desc, scenario_2_when, scenario_2_desc,
         ai_hurt, bubble}

    Raises:
        KeyError: 알 수 없는 일간.
    """
    if ilgan not in VALID_ILGAN:
        raise KeyError(f"unknown ilgan: {ilgan!r}")

    (when_1, desc_1), (when_2, desc_2) = HURT_SCENARIOS_BY_ILGAN[ilgan]
    ai = HURT_AI_BY_ILGAN[ilgan].format(
        ilgan_with_hanja=_ilgan_with_hanja(ilgan)
    )

    return {
        "scenario_1_when": when_1,
        "scenario_1_desc": desc_1,
        "scenario_2_when": when_2,
        "scenario_2_desc": desc_2,
        "ai_hurt": ai,
        "bubble": HURT_BUBBLE_BY_ILGAN[ilgan],
    }
